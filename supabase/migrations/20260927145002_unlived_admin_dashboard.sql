-- UNLIVED admin foundation: catalogue, order records and contact inbox.
-- The public website does not accept payments yet; orders stay empty until checkout exists.

create schema if not exists private;

create table public.admin_users (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

create table public.products (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  title text not null check (char_length(title) between 2 and 120),
  collection text not null default 'ACTE I: DAY ONE',
  category text not null default 'T-shirt',
  description text not null default '',
  status text not null default 'draft' check (status in ('draft', 'active', 'archived')),
  featured boolean not null default false,
  price_cents integer check (price_cents is null or price_cents >= 0),
  currency text not null default 'EUR' check (currency ~ '^[A-Z]{3}$'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.product_variants (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.products (id) on delete cascade,
  color_name text not null check (char_length(color_name) between 2 and 40),
  color_slug text not null check (color_slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  color_hex text not null default '#E8E4DC' check (color_hex ~ '^#[0-9A-Fa-f]{6}$'),
  sku text unique,
  stock_quantity integer check (stock_quantity is null or stock_quantity >= 0),
  is_available boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (product_id, color_slug)
);

create table public.product_media (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.products (id) on delete cascade,
  variant_id uuid references public.product_variants (id) on delete cascade,
  media_type text not null default 'image' check (media_type in ('image', 'video')),
  url text not null check (char_length(url) between 1 and 2048),
  alt_text text not null default '',
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_name text not null,
  customer_email text not null,
  status text not null default 'pending' check (status in ('pending', 'processing', 'shipped', 'delivered', 'cancelled', 'refunded')),
  total_cents integer check (total_cents is null or total_cents >= 0),
  currency text not null default 'EUR' check (currency ~ '^[A-Z]{3}$'),
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders (id) on delete cascade,
  product_id uuid references public.products (id) on delete set null,
  product_title text not null,
  variant_name text not null default '',
  quantity integer not null check (quantity > 0),
  unit_price_cents integer check (unit_price_cents is null or unit_price_cents >= 0)
);

create table public.contact_messages (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 1 and 120),
  email text not null check (char_length(email) between 3 and 254),
  message text not null check (char_length(message) between 1 and 5000),
  status text not null default 'new' check (status in ('new', 'read', 'archived')),
  created_at timestamptz not null default now()
);

create index product_variants_product_id_idx on public.product_variants (product_id);
create index product_media_product_order_idx on public.product_media (product_id, sort_order);
create index orders_created_at_idx on public.orders (created_at desc);
create index orders_customer_email_idx on public.orders (lower(customer_email));
create index contact_messages_status_created_at_idx on public.contact_messages (status, created_at desc);

create function private.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

revoke all on function private.set_updated_at() from public, anon, authenticated;

create trigger products_set_updated_at before update on public.products
for each row execute function private.set_updated_at();
create trigger product_variants_set_updated_at before update on public.product_variants
for each row execute function private.set_updated_at();
create trigger orders_set_updated_at before update on public.orders
for each row execute function private.set_updated_at();

alter table public.admin_users enable row level security;
alter table public.products enable row level security;
alter table public.product_variants enable row level security;
alter table public.product_media enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.contact_messages enable row level security;

grant select on public.admin_users to authenticated;
grant select on public.products, public.product_variants, public.product_media to anon, authenticated;
grant insert, update, delete on public.products, public.product_variants, public.product_media to authenticated;
grant select, insert, update, delete on public.orders, public.order_items to authenticated;
grant insert on public.contact_messages to anon, authenticated;
grant select, update, delete on public.contact_messages to authenticated;
grant usage, select on sequence public.orders_order_number_seq to authenticated;

create policy "Admins can verify their own access" on public.admin_users
for select to authenticated using (user_id = (select auth.uid()));

create policy "Public can view active products" on public.products
for select to anon, authenticated using (status = 'active');
create policy "Admins can manage products" on public.products
for all to authenticated
using (exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())))
with check (exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())));

create policy "Public can view available variants of active products" on public.product_variants
for select to anon, authenticated using (
  is_available and exists (
    select 1 from public.products p where p.id = product_id and p.status = 'active'
  )
);
create policy "Admins can manage product variants" on public.product_variants
for all to authenticated
using (exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())))
with check (exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())));

create policy "Public can view media for active products" on public.product_media
for select to anon, authenticated using (
  exists (select 1 from public.products p where p.id = product_id and p.status = 'active')
);
create policy "Admins can manage product media" on public.product_media
for all to authenticated
using (exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())))
with check (exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())));

create policy "Admins can manage orders" on public.orders
for all to authenticated
using (exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())))
with check (exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())));
create policy "Admins can manage order items" on public.order_items
for all to authenticated
using (exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())))
with check (exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())));

create policy "Anyone can send a contact message" on public.contact_messages
for insert to anon, authenticated with check (true);
create policy "Admins can read contact messages" on public.contact_messages
for select to authenticated
using (exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())));
create policy "Admins can update contact messages" on public.contact_messages
for update to authenticated
using (exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())))
with check (exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())));
create policy "Admins can delete contact messages" on public.contact_messages
for delete to authenticated
using (exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())));

